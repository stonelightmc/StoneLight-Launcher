window.sllTranslateMessage = function (message) {
  if (message === null || message === undefined) return message;
  const lang = window.SLLState?.preferences?.language || "en";
  const source = String(message);
  const mapping = window.SLL_MESSAGE_I18N[lang] || {};
  const exact = mapping[source];
  if (exact !== undefined) return exact;

  let result = source;
  const hasCyrillic = value => /[А-Яа-яЁёІіЇїЄєҐґ]/.test(value);
  const entries = Object.entries(mapping).sort((a, b) => b[0].length - a[0].length);
  for (const [src, dst] of entries) {
    if (!src || !hasCyrillic(src) || !result.includes(src)) continue;
    result = result.split(src).join(dst);
  }
  return result;
};
